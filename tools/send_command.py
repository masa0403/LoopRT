from looprt import send_commands



PORT = "/dev/ttyUSB0"

commands = [

    # ========================================================
    # 1. H() + I()
    # ========================================================

    # D8 HIGH
    "H(8)\n",

    # HIGHになったことを確認
    "I(8)\n",

    # 安定待ち
    "D(500)\n",


    # ========================================================
    # 2. L() + I()
    # ========================================================

    # D8 LOW
    "L(8)\n",

    # LOWになったことを確認
    "I(8)\n",

    # 安定待ち
    "D(500)\n",


    # ========================================================
    # 3. P() + PI()
    # ========================================================

    # D9 = 25% PWM
    "P(9,25)\n",

    # RC + ADCが安定するまで待つ
    "D(1000)\n",

    # D7でTarget PA2のPWMを観測
    "PI(7)\n",


    # --------------------------------------------------------
    # 50%
    # --------------------------------------------------------

    "P(9,50)\n",

    "D(1000)\n",

    "PI(7)\n",


    # --------------------------------------------------------
    # 75%
    # --------------------------------------------------------

    "P(9,75)\n",

    "D(1000)\n",

    "PI(7)\n",


    # ========================================================
    # 4. 0% / 100%も確認
    # ========================================================

    "P(9,0)\n",

    "D(1000)\n",

    "PI(7)\n",

    "P(9,100)\n",

    "D(1000)\n",

    "PI(7)\n",


    # ========================================================
    # 5. 終了
    # ========================================================

    "E\n"
]
result = send_commands(PORT, commands)

print(result)

